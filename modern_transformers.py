# Typically installed via: pip install transformers torch
from transformers import AutoTokenizer, AutoModel
import torch

# 1. Load a lightweight, industry-standard Transformer model and its matching tokenizer
# DistilBERT is a smaller, faster version of BERT
model_name = "distilbert-base-uncased"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModel.from_pretrained(model_name)

# 2. Prepare text input
text = "AI Engineering requires understanding Deep Learning foundations."

# 3. Tokenize the text (converts string to token IDs and creates an attention mask)
inputs = tokenizer(text, return_tensors="pt")
print("Tokenized Inputs (Dict of Tensors):", inputs.keys())
print("Token IDs array:", inputs['input_ids'])

# 4. Forward pass through the Transformer model
model.eval() # Always set to evaluation mode for inference!
with torch.no_grad():
    outputs = model(**inputs)

# 5. Extract the "Last Hidden State"
# This is the final layer of vectors generated by the Transformer layers
last_hidden_states = outputs.last_hidden_state

print("\nOutput Shape from Transformer Layer:", last_hidden_states.shape)
# Shape explanation: [1 batch, 10 tokens generated, 768 embedding dimensions per token]
